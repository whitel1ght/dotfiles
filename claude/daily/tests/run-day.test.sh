#!/usr/bin/env bash
# Structure checks for commands/run-day.md: the rules the spec fixes, and the contracts with the mod.
set -uo pipefail
TEST_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$TEST_DIR/lib.sh"
F="$TEST_DIR/../commands/run-day.md"

echo "== frontmatter =="
frontmatter_has "$F" description
frontmatter_has "$F" argument-hint

echo "== rules from the spec =="
has "$F" "Subagents never write to \`~/wiki\`" "subagents never write the vault"
has "$F" "except \`~/wiki/work/system/\` and \`~/wiki/tools/\`" "subagents may write the system and tools pages"
has "$F" "<!-- start-day:start -->" "reads the start-day block"
has "$F" "fewer than **3** ticket agents" "cap of 3 agents"
has "$F" "\`[ ]\` todo, \`[/]\` in progress, \`[X]\` done (an older \`[x]\` counts too), \`[!]\` blocked, \`[>]\` deferred to tomorrow" "marker legend"
has "$F" "git -C <worktree> diff --stat" "check-before-tick reads the diff"
has "$F" "PushNotification" "second failure notifies"
has "$F" "405" "merge 405 rule"
has "$F" "/orchestrate" "reuses orchestrate by reference"
has "$F" "wt add <repo> <KEY>" "worktrees via wt"
has "$F" "\${CLAUDE_PLUGIN_ROOT}/templates/ticket-brief.md" "uses the ticket brief"
has "$F" "\${CLAUDE_PLUGIN_ROOT}/templates/review-round-brief.md" "uses the review-round brief"
has "$F" "no draft-only mode" "records the mr-review-response limitation"
has "$F" '-F "body=@<reply file>"' "posts the reply with glab api"
has "$F" "file the round as a decision (section 9)" "one decision per round"
has "$F" "option 1 is \`yes\`, option 3 is \`no\`" "maps the answer onto yes / no / edit"
has "$F" "markdown link with the repo in the link text" "MR link rule"
has "$F" "dry run: nothing created" "dry-run ending line"
has "$F" "changes-since --cursor run-day >/dev/null" "seeds the watcher cursor right after creating the run state"
has "$F" "PROJECT_PATH=" "derives the glab project path from the event url"
has "$F" "_templates/decision.md" "decision frontmatter comes from the vault template"

echo "== contract with the mod =="
has "$F" "[daily-event] <kind> | <repo>!<iid> | <TICKET> | <summary> | <url>" "event line format matches mod/events.ts formatPrompt"
has "$F" "[daily-event:info]" "informational lines"
line="$(grep -m1 '^- ecfx-18169 | class=auto' "$F")"
order="$(printf '%s' "$line" | tr '|' '\n' | sed -n 's/^ *\([a-z_]*\)=.*/\1/p' | tr '\n' ' ' | sed 's/ $//')"
[ "$order" = "class agent round worktree mr retries needs_you owner" ] && pass "run-state example has the fields mod/runstate.ts reads, in order" \
  || fail "run-state field order" "got [$order]"
has "$F" "inbox: <N> new" "handles the mod's inbox prompt"
has "$F" "**Unplanned**" "uses the group name mod/view.ts orders last"
has "$F" "owner=external:<KEY>" "writes the owner the mod parser reads"
W="$TEST_DIR/../mod/wake.ts"
has "$F" "[daily-wake] woke after" "handles the wake prompt of mod/wake.ts wakePrompt"
has "$W" '${WAKE_PREFIX} woke after ' "wakePrompt still says woke after"
has "$F" "[daily-wake] stuck: <KEY> <id>, …" "handles the stuck prompt of mod/wake.ts stuckPrompt"
has "$W" '${WAKE_PREFIX} stuck: ${rows.map(r => `${r.key} ${r.id}`).join('"', '"')}' "stuckPrompt still lists key and id"
has "$W" "Run the Wake check of /daily:run-day (section 10)" "the wake prompts name section 10"
has "$F" "## 10. Wake check" "section 10 is the Wake check"
has "$F" "~/.local/state/run-day/\$(date +%F).agents" "reads the agents file register.tsx writes"
has "$F" "Header \`# agents <ISO time>\`" "agents-file header as mod/wake.ts formatAgents writes it"
has "$W" '`# agents ${new Date(now).toISOString()}`' "formatAgents still writes the ISO header"
has "$F" "\`<key> | ticket|round | <id> | <status> | quiet=<minutes|-> | <transcript|->\`" "agents-file row as mod/wake.ts formatAgents writes it"
has "$W" '`${r.key} | ${r.kind} | ${r.id} | ${r.status} | quiet=${quiet} | ${r.transcript || '"'-'"'}`' "formatAgents still writes that row"

echo "== inbox (spec 4.9) =="
has "$F" "~/.local/state/run-day/inbox/" "reads the inbox directory"
has "$F" '`done`, `progress`, `handback`, `offplan`' "knows the four kinds"
has "$F" "oldest first" "processes oldest first"
has "$F" 'inbox/done/$T/' "moves processed messages to done/<date>"
has "$F" "inbox/bad/" "moves malformed messages to bad/"
has "$F" "a key that is not on the plan" "a done for an unplanned key becomes off-plan work"
has "$F" "worktree is gone" "recovers a handback whose worktree was deleted"
has "$F" "second message for the same key" "two messages for one key update one line"
has "$F" "never downgrade" "a late progress never reopens a ticked line"
has "$F" 'apply the `memory:` block (section 4)' "every kind applies the memory block"
has "$F" "do not spawn a review-round agent for it" "no review round for an item in a side session"
has "$F" "handling any other event or agent report" "checks the inbox on every event"
has "$F" "/loop 5m" "no-mod fallback polls the inbox"
has "$F" "owner=main" "a handback returns the item to the main session"

echo "== fix round 1 =="
has "$F" "not mentioned in any output, even if they appear in \`ls\`" "non-message files are never named in output"
has "$F" "merged in the UI by you" "dry run states merge rows are merged in the UI"
has "$F" 'with the branch from `glab mr view`' "wt add with the MR branch for items that have one"
has "$F" "an old decision's \`status\` (only to \`superseded\`)" "write rules allow superseding an old decision"
has "$F" "\`done\` replaces any existing" "done replaces earlier evidence suffixes"
has "$F" "no run-state line" "inbox keys without a run-state line"
has "$F" "comes from the agent's \`discussion:\` report line" "discussion id source"
has "$F" "grep -c '{{'\` on the filled review-round brief" "review-round brief leftover check"
has "$F" "{{REPLY_FILE}}, {{REPO}}, {{WORKTREE}}" "lists all ten placeholders"

echo "== shell state: every Bash call is a new shell =="
has "$F" "Each Bash call is a new shell" "states the fresh-shell rule"
# every fenced block that uses a variable must also set it
block_sets() { awk -v use="$2" -v set="$3" '/^```/{if(inb){if(u&&!d)bad=1;inb=0;u=d=0}else inb=1;next} inb&&index($0,use){u=1} inb&&index($0,set){d=1} END{exit bad}' "$1"; }
for pair in 'LOGF=|P=' 'LOGF=|Q=' '$ENC|ENC=' '$IID|IID=' '$INBOX|INBOX=' '$T/|T=' '$f"|f='; do
  u="${pair%%|*}"; d="${pair##*|}"
  block_sets "$F" "$u" "$d" && pass "blocks using $u set $d" || fail "blocks using $u set $d" "a Bash block relies on $d from another call"
done


echo "== keep busy: reviews are agent work, the sprint fills free slots (2026-10-29) =="
B="$TEST_DIR/../mod/busy.ts"
has "$F" "**review**: someone else's MR to review or re-review" "triage has a review class"
has "$F" "\${CLAUDE_PLUGIN_ROOT}/templates/review-brief.md" "uses the review brief"
has "$F" "\`<repo letters>-<iid>\`" "tracks a review without a ticket key"
has "$F" "e.g. \`claudecomponents-55\`" "the review key passes the inbox key check"
lacks "$F" "its key is \`review-" "no review key the inbox check would reject"
printf 'claudecomponents-55\n' | grep -Eq '^[A-Za-z][A-Za-z0-9]*-[0-9]+$' && pass "example review key matches the inbox key pattern" || fail "review key pattern" "claudecomponents-55"
has "$F" "· ready locally, waiting on Take it" "a not-yours-yet report is not checked for an MR"
has "$F" "-f sha=<reviewed sha>" "approval is pinned to the reviewed head"
has "$F" "Post the review of" "posting a review is one decision"
has "$F" "## 11. Keep busy" "section 11 is Keep busy"
has "$F" "Never end a turn saying the rest is the user's" "no idle hand-back while work remains"
has "$F" "jt --list -m" "reads the user's sprint tickets"
has "$F" "jt --list -u" "reads the team's unassigned sprint tickets"
has "$F" "**From the sprint**" "pulled tickets get their own plan group"
has "$F" "Take <KEY> from the sprint?" "an unassigned ticket is taken on the user's yes"
has "$F" "[daily-idle] no agent running" "handles the idle prompt"
has "$B" "run Keep busy of /daily:run-day (section 11)" "busy.ts still names section 11"
has "$F" "Keep busy (section 11) found nothing" "finish only after the sprint is empty"
P="$TEST_DIR/../../../pi/prompts/run-day.md"
has "$P" "## 11. Keep busy" "pi: section 11 is Keep busy"
has "$P" "Never end a turn saying the rest is the user's" "pi: no idle hand-back while work remains"
has "$P" "jt --list -m" "pi: reads the sprint"
has "$P" "templates/review-brief.md" "pi: uses the review brief"
has "$P" "[daily-idle] no agent running" "pi: handles the idle prompt"
has "$B" "run Keep busy of /run-day (section 11)" "busy.ts pi prompt still names section 11"

echo "== decision queue =="
has "$F" "## 9. Decisions" "has a decisions section"
has "$F" "decide add --key" "files decisions with decide add"
has "$F" "decision D-<n> queued: <question>" "one thread line per decision"
has "$F" "never ask the question in the thread" "no questions in the thread"
has "$F" "\`done\`, \`progress\`, \`handback\`, \`offplan\`, \`service\`, \`decision\`, \`clarify\`" "inbox accepts the two new kinds"
has "$F" "\`decision\`: run \`decide show <id>\`" "applies an answer"
has "$F" "\`clarify\`: answer with \`decide reply <id> " "answers a question back in the decision"
has "$F" "For every kind but \`service\`, \`decision\` and \`clarify\`" "no memory block for the new kinds"

echo "== decision queue: review fixes =="
has "$F" "no diary change and no Unplanned line, whatever the key" "answers never write diary lines"
has "$F" "withdraw and close the old decision first" "edit after a question back does not deadlock"
has "$F" "Change the reply first (add a note with n)" "option 2 names the popup's note key"
lacks "$F" "on their yes" "resume re-dispatch is a decision"
lacks "$F" "ask the user for the MR link" "a missing MR link is a decision"
lacks "$F" "post it only if the user says so" "the Jira one-liner is a decision"
lacks "$F" "offer to add the ticket to today's plan; on yes" "a new assignment is a decision"

finish
