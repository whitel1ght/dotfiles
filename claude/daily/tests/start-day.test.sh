#!/usr/bin/env bash
# Structure checks for the coach step in the start-day playbooks (both harnesses).
set -uo pipefail
TEST_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$TEST_DIR/lib.sh"
C="$TEST_DIR/../../commands/start-day.md"
P="$TEST_DIR/../../../pi/prompts/start-day.md"

for f in "$C" "$P"; do
  side="$(basename "$(dirname "$f")")"
  echo "== $side =="
  has "$f" "## 4. Coach" "$side: coach step exists"
  lacks "$f" "~/.local/bin/words" "$side: no word of the day or lookups (out of the day, 2026-11-13)"
  lacks "$f" "cards due" "$side: no card quiz"
  lacks "$f" "cards grade" "$side: nothing is graded"
  lacks "$f" "~/.local/bin/drills" "$side: no drill window"
  lacks "$f" "merriam-webster word of the day" "$side: the diary habit line is never written"
  has "$f" '`repos-sync` has fetched every GitLab repo' "$side: the digest's Repos section is explained"
  has "$f" "setup, not work: keep them out of the plan" "$side: repos stay out of the plan"
  has "$f" '`team-plugins-sync` has updated the' "$side: the Team plugins section is explained"
  has "$f" "## 5. File it" "$side: File it is renumbered"
  has "$f" '`## QA candidates`' "$side: the digest's QA candidates section is read"
  has "$f" "QA (claude-components qa flow)" "$side: QA items keep the 10-27 line form"
  has "$f" "only those marked \`QA: unclaimed\`" "$side: only unclaimed tickets are proposed"
  has "$f" "at most two" "$side: two QA items at most"
  has "$f" "each unclaimed QA candidate" "$side: the pre-write check covers QA candidates"
  lacks "$f" "## 4. File it" "$side: no stale File it number"
  awk '/^## 3\. Write the plan/{a=NR} /^## 4\. Coach/{b=NR} /^## 5\. File it/{c=NR} END{exit !(a&&b&&c&&a<b&&b<c)}' "$f" && pass "$side: coach sits between plan and File it" || fail "$side: order" "wrong order in $f"
  coach="$(awk '/^## 4\. Coach/{on=1} /^## 5\. File it/{on=0} on' "$f")"
  grep -qE '\$T([^A-Za-z_]|$)' <<<"$coach" && fail "$side: no bare \$T in the coach step" "$(grep -nE '\$T([^A-Za-z_]|$)' <<<"$coach")" || pass "$side: no bare \$T in the coach step"
  has "$f" "friction-cards count" "$side: counts the friction queue"
  has "$f" "friction queue: N waiting" "$side: prints the queue line"
  lacks "$f" "coach-offer" "$side: no coach offer"
  lacks "$f" "coach-answer" "$side: no coach answer"
  has "$f" "Nothing from this step goes into the diary" "$side: no-diary rule"
  has "$f" "never mentions the coach" "$side: plan text stays coach-free"
  has "$f" "friction-ledger coach-log --date" "$side: logs the counts"
  has "$f" "### Monthly tool review" "$side: monthly review subsection"
  has "$f" "Monthly tool review: run it now? (yes/no)" "$side: monthly offer line"
  lacks "$f" "procedure added in Task 7" "$side: no placeholder left in the monthly review"
  has "$f" "start ONE research subagent in the background" "$side: monthly review runs one background subagent"
  has "$f" "coach-mine --commands --date <T>" "$side: review counts usage with coach-mine --commands"
  has "$f" "ls ~/projects/dotfiles/bin" "$side: review inventories bin/"
  has "$f" "\`switch\` (clearly better), \`try\`" "$side: verdicts switch / try / keep"
  has "$f" "friction-ledger add-tool --sig tool:<name> --proposal-file <file> --date <T>" "$side: switch and try are recorded with add-tool"
  has "$f" "Never record a \`keep\`" "$side: keep verdicts are not recorded"
  has "$f" "never install" "$side: review never installs"
  has "$f" "do not wait" "$side: the session does not wait for the review"
  has "$f" "never blocks the plan" "$side: coach never blocks the plan"
  has "$f" "day-agent init" "$side: the agent file is created before save"
  has "$f" "day-agent mr <key>" "$side: MRs go to the agent file"
  has "$f" "day-agent note <key> carried" "$side: carried facts go to the agent file"
  has "$f" "at most 100 characters" "$side: plan lines are short"
  has "$f" "<!-- pN -->" "$side: keyless lines carry a comment id"
  lacks "$f" "backend !6390" "$side: merge example uses repo!iid"
  lacks "$f" "@bob" "$side: examples name people without @"
  has "$f" "day-agent id" "$side: the id comes from day-agent"
  has "$f" '## My draft MRs' "$side: reads the draft list"
  has "$f" 'ship <repo>!<iid>' "$side: a finished draft becomes a ship line"
  has "$f" 'undraft X once Y' "$side: no step waits on a dependency to undraft"
  lacks "$f" 'already approved or drafts' "$side: drafts are no longer left out wholesale"
  lacks "$f" "trailing \`[↗][label]\` ref" "$side: no [↗] refs in the plan"
  lacks "$f" "inline \`[dashboard!940](url)\`" "$side: no inline MR links in the plan"
  has "$f" '-in:<@USDTCL35J> -from:<@USDTCL35J>' "$side: the DM search leaves out the Jira app's DMs"
  has "$f" 'im,mpim' "$side: it covers DMs and group DMs"
  has "$f" 'with no page limit' "$side: it pages to the end"
  lacks "$f" 'filter `is:dm`' "$side: no is:dm search the Jira app can crowd out"
  lacks "$f" 'up to five pages' "$side: no page cap"
  has "$f" '`## Jira mentions of me`' "$side: the digest's Jira mentions are read"
  has "$f" 'each Jira mention awaiting a reply' "$side: the pre-write check covers Jira mentions"
  has "$f" 'each DM or group' "$side: DM and group DM requests go under First"
  has "$f" '`## Still open from earlier' "$side: the digest's still-open items are read"
  has "$f" 'never closes it' "$side: leaving an item off never closes it"
  has "$f" 'Never dismiss or drop one yourself' "$side: the model never dismisses on its own"
  has "$f" 'dismissed "the user said: <what>"' "$side: a dismissal records the user's word"
  has "$f" '"from <ref>: <facts>"' "$side: a keyless item keeps its identity"
  has "$f" 'still open but not on this plan' "$side: save's note is acted on"
  lacks "$f" 'each unticked carry-over item' "$side: no carry-over-only check"
done

has "$C" "Bash(~/.local/bin/day-agent:*)" "claude: allows day-agent"
has "$C" "Bash(day-agent:*)" "claude: allows the bare day-agent the text calls"
lacks "$C" "Bash(~/.local/bin/words:*)" "claude: no words permission"
lacks "$C" "Bash(~/.local/bin/drills:*)" "claude: no drills permission"
lacks "$C" "Bash(~/.local/bin/cards:*)" "claude: no cards permission"

finish
